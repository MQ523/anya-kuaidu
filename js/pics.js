  function p(e, l, svgName) {
    return { e, l, svg: svgName ? SVG[svgName] : "" };
  }

  function fromChar(ch) {
    return CHAR[ch] || null;
  }

  function fromWord(text) {
    if (WORD[text]) return [WORD[text]];
    const pics = [];
    const seen = new Set();
    for (const ch of text) {
      const hit = CHAR[ch];
      if (hit && !seen.has(hit.e)) {
        seen.add(hit.e);
        pics.push(hit);
      }
      if (pics.length >= 3) break;
    }
    return pics;
  }

  function forItem(item) {
    if (!item) return [];
    if (item.kind === "char") {
      const hit = fromChar(item.z);
      return hit ? [hit] : [];
    }
    if (item.kind === "word") return fromWord(item.z);
    const pics = [];
    const seen = new Set();
    const words = Object.keys(WORD).sort((a, b) => b.length - a.length);
    let rest = item.z;
    words.forEach((word) => {
      if (pics.length >= 4) return;
      if (rest.includes(word) && WORD[word] && !seen.has(WORD[word].e)) {
        seen.add(WORD[word].e);
        pics.push(WORD[word]);
        rest = rest.split(word).join(" ");
      }
    });
    if (pics.length < 3) {
      for (const ch of rest) {
        const hit = CHAR[ch];
        if (hit && !seen.has(hit.e)) {
          seen.add(hit.e);
          pics.push(hit);
        }
        if (pics.length >= 4) break;
      }
    }
    if (!pics.length) return fromWord(item.z);
    return pics;
  }

  function html(item, extraClass) {
    const pics = forItem(item);
    if (!pics.length) return "";
    const bubbles = pics
      .map((pic) => `<span class="pic-bubble">${pic.svg || pic.e}</span>`)
      .join("");
    const label = pics[0] && pics[0].l ? pics[0].l : "";
    return `<div class="pic-stage ${extraClass || ""}">${bubbles}${
      label ? `<p class="pic-label">${label}</p>` : ""
    }</div>`;
  }

